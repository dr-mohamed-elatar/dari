/// خريطة مراكز وقرى بني سويف مدمجة لإكمال عنوان العميل/الضامن.
const Map<String, List<String>> beniSuefCenters = {
  'بني سويف': ['بني سويف المدينة', 'البياضة', 'القراينة', 'شرق النيل', 'الكوم الأحمر', 'بني هارون', 'تزمنت الشرقية'],
  'الواسطى': ['الواسطى المدينة', 'أبو صير الملق', 'إنفسط', 'أطواب', 'قمن العروس', 'الميمون'],
  'ناصر': ['ناصر المدينة', 'بني عدي', 'الشناوية', 'أشمنت', 'دنديل', 'الحمام'],
  'إهناسيا': ['إهناسيا المدينة', 'العواونة', 'البرشا', 'منهرو', 'شدنتو', 'الكلابية'],
  'ببا': ['ببا المدينة', 'طملية', 'غياضة الشرقية', 'كوم أبو خليل', 'دشطوت', 'هماس'],
  'سمسطا': ['سمسطا المدينة', 'مازورا', 'دشطوط', 'بدهل', 'شلب', 'كفر درب'],
  'الفشن': ['الفشن المدينة', 'الفنت', 'تلت', 'شنرا', 'بنى سليمان', 'أبو سلطان'],
  'مغاغة': ['مغاغة المدينة', 'بني خالد', 'الجعافرة', 'أم البركات', 'الخضراوية', 'طه العميدين'],
  'أبو صير': ['أبو صير المدينة', 'المنشية الكبرى'],
};

List<String> beniSuefAddressSuggestions(String query) {
  final q = query.trim();
  if (q.isEmpty) return [];
  final out = <String>[];
  beniSuefCenters.forEach((center, villages) {
    if (center.contains(q)) out.add(center);
    for (final v in villages) {
      if (v.contains(q)) out.add('$v، $center');
    }
  });
  return out.take(8).toList();
}
